#!/usr/bin/env python3
"""Render the evidence parts of docs/zetaris_usl/ from the saved results -- nothing typed by hand.

    python3 scripts/zetaris_eval.py              # run live, save docs/zetaris_usl/results/*.json
    python3 scripts/handcoded_comparison.py      # 2a measurements
    python3 scripts/zetaris_docs.py              # then render

Writes 02_exploratory_queries.md and 03_usl.md in full, and the measured block of
04_time_saved.md between its `<!-- BEGIN generated -->` / `<!-- END generated -->` markers.
The planted-error count for the DQ rule is computed from the committed answer key
(data/synthetic/ground_truth.json), not stated.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs" / "zetaris_usl"
RESULTS = DOCS / "results"
USL_DIR = ROOT / "data" / "zetaris" / "usl"
SOURCES_1B = ["Hospital EMR", "GP", "Community pharmacy", "Patient interview", "PBS medicines lexicon",
              "ACSQHC APINCHS"]
HEADER = ("<!-- Generated by scripts/zetaris_docs.py from docs/zetaris_usl/results/*.json. "
          "Do not edit by hand: re-run the scripts. -->\n\n")


def _load(qid: str) -> dict:
    return json.loads((RESULTS / f"{qid}.json").read_text())


def _cell(v) -> str:
    return "∅" if v is None else str(v).replace("|", "\\|").replace("\n", " ")


def _table(headers: list, rows: list) -> str:
    if not headers:
        return "_(no columns returned)_\n"
    out = ["| " + " | ".join(map(str, headers)) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(_cell(v) for v in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def _evidence(e: dict, *, columns: list[str] | None = None) -> str:
    rows, headers = e["first_rows"], e["headers"]
    if columns:
        idx = [headers.index(c) for c in columns]
        headers, rows = columns, [[r[i] for i in idx] for r in rows]
    more = f" (first {len(rows)} shown)" if e["row_count"] and e["row_count"] > len(rows) else ""
    return (f"```sql\n{e['sql']}\n```\n\n{_table(headers, rows)}\n"
            f"<sub>{e['row_count']} rows{more} · {e['latency_ms']:,} ms · run {e['executed_at']} UTC "
            f"via `{e['client']}` · [`results/{e['id']}.json`](results/{e['id']}.json)</sub>\n")


def _ddl() -> str:
    out = []
    for path in sorted(USL_DIR.glob("[0-9][0-9]_usl_*.sql")):
        out.append(f"**`data/zetaris/usl/{path.name}`**\n\n```sql\n{path.read_text().strip()}\n```\n")
    return "\n".join(out)


def render_02() -> str:
    index = json.loads((RESULTS / "index.json").read_text())["results"]
    parts = [HEADER, "# 1b — Onboard the sources, verify them, explore them\n\n",
             "Each source is registered in Zetaris (how: [01](01_use_case_and_sources.md)) and was queried "
             "live through MedTrace's own read-only Zetaris adapter. Every result below is the saved output "
             "of `scripts/zetaris_eval.py`.\n\n"]
    for source in SOURCES_1B:
        mine = [r for r in index if r["part"] == "1b" and r["source"] == source]
        parts.append(f"## {source} ({len(mine)} queries)\n\n")
        for r in mine:
            e = _load(r["id"])
            parts.append(f"### {e['question']}\n\n{_evidence(e)}\n")
    return "".join(parts)


def _planted_check() -> tuple[int, int, int]:
    """(violations, of which planted dose errors, planted dose errors in total)."""
    e = _load("1c_dq_invalid")
    rows = e.get("all_rows") or e["first_rows"]
    ids = {r[e["headers"].index("row_id")] for r in rows}
    gt = json.loads((ROOT / "data" / "synthetic" / "ground_truth.json").read_text())
    dose_rows = {rid for p in gt["patients"] for f in p.get("planted", []) if f.get("type") == "dose"
                 for rid in f.get("row_ids", [])}
    planted_dose = sum(1 for p in gt["patients"] for f in p.get("planted", []) if f.get("type") == "dose")
    return len(ids), len(ids & dose_rows), planted_dose


def render_03() -> str:
    run = _load("1c_dq_run")
    total, valid, invalid = (run["first_rows"][0][run["headers"].index(k)]
                             for k in ("total_record", "valid_record", "invalid_record"))
    fk = _load("1c_dq_fk")
    fk_invalid = fk["first_rows"][0][fk["headers"].index("invalid_record")]
    n, planted, planted_total = _planted_check()
    lines = [HEADER, "# 1c — The Unified Semantic Layer: build, verify, quality state\n\n",
             "**`lightning.metastore.medtrace.medtrace_usl`** — one semantic model, three related tables, "
             "six registered sources. Created live on Zetaris with the DDL below "
             "(`python3 scripts/register_sources.py --usl --apply`; dry run without `--apply`).\n\n",
             "```mermaid\nflowchart LR\n"
             "  EMR[(Hospital EMR<br/>AMT product codes)] --> AS[medtrace.all_sources]\n"
             "  GP[(GP<br/>AMT pack codes)] --> AS\n"
             "  PH[(Community pharmacy<br/>PBS codes / private brands)] --> AS\n"
             "  PT[(Patient interview<br/>free text)] --> AS\n"
             "  LX[(PBS medicines lexicon)] --> MED[medicine]\n"
             "  AP[(ACSQHC APINCHS)] --> HR[high_risk_class]\n"
             "  AS --> MS[medication_statement]\n  LX --> MS\n  AP --> MS\n"
             "  MS -- \"FK generic\" --> MED\n"
             "  subgraph USL[\"USL medtrace_usl\"]\n    MED\n    HR\n    MS\n  end\n"
             "  DQ{{\"DQ: strength_is_a_real_product\"}} -.-> MS\n```\n\n",
             "Every source codes medicines its own way — the EMR by AMT medicinal product, the GP by AMT "
             "*pack*, the pharmacy by PBS item (or, for private scripts, only a brand), the patient in their "
             "own words. `medication_statement` resolves all of that **once**, in its activation query; every "
             "question after that is a single `SELECT`.\n\n",
             "## The DDL\n\n", _ddl(), "\n",
             "## The USL is active\n\n"]
    for qid in ("1c_usl_tables", "1c_usl_1", "1c_usl_2", "1c_usl_3"):
        e = _load(qid)
        lines.append(f"### {e['question']}\n\n{_evidence(e)}\n")
    lines += ["## Data quality: native Zetaris rules\n\n",
              f"**Custom rule `strength_is_a_real_product` executed: {invalid} of {total} records invalid "
              f"({valid} valid).** A line naming a medicine and a strength must name a strength that medicine "
              "is made in — `amlodipine 2.5 mg` fails because amlodipine comes as 5 mg and 10 mg.\n\n",
              f"**Checked against the answer key:** {planted} of the {n} violations are planted chart-dose "
              f"errors. The rule catches {planted} of the {planted_total} planted dose errors; the rest chart "
              "a strength that *is* a real product (20 mg where 10 mg is right), which only a cross-source "
              "comparison can see — that is MedTrace's detector's job, not a single-table rule's.\n\n",
              f"**The foreign-key rule (`generic` → `medicine`) reports {fk_invalid} invalid records** — "
              "exactly the patient-interview lines, which carry no code and so no resolved medicine. Zetaris "
              "counts a NULL foreign key as invalid. That is a true statement about the data: those lines "
              "can only be matched downstream (MedTrace does it with the lexicon and a constrained model "
              "choice), not by code.\n\n"]
    for qid in ("1c_dq_list", "1c_dq_run", "1c_dq_fk"):
        e = _load(qid)
        lines.append(f"### {e['question']}\n\n{_evidence(e)}\n")
    e = _load("1c_dq_invalid")
    lines.append(f"### {e['question']}\n\n" + _evidence(
        e, columns=["row_id", "patient_id", "record_kind", "generic", "strength_text", "freq_text"]) + "\n")
    return "".join(lines)


def render_04_block() -> str:
    r = json.loads((RESULTS / "2a_handcoded_comparison.json").read_text())
    u, h = r["usl"], r["hand_coded"]
    rows = [["Code to answer this question", "1 SQL statement", f"{h['lines_of_code']} lines of Python"],
            ["One-time setup", f"{u['one_time_activation_sql_lines']} lines of activation SQL (reused by every query)",
             "none (but nothing is reused)"],
            ["Manual mapping steps at question time", "0", str(h["manual_mapping_steps"])],
            ["Runtime", f"{u['runtime_s']} s", f"{h['runtime_s']} s"],
            ["Result", f"{u['rows']} rows", f"{h['rows']} rows"],
            ["Identical results", "yes" if r["results_match_exactly"] else "NO", ""]]
    steps = "\n".join(f"{i}. {s}" for i, s in enumerate(h["mapping_steps"], 1))
    diff = ("" if r["results_match_exactly"] else
            "\n**Differences:**\n\n" + _table(["class", "source", "USL", "hand-coded"],
                                             [[d["high_risk_class"], d["source"], d["usl"], d["hand_coded"]]
                                              for d in r["differences"]]))
    return (f"<!-- BEGIN generated -->\n<sub>Measured {r['executed_at']} UTC by `scripts/handcoded_comparison.py` · "
            f"[`results/2a_handcoded_comparison.json`](results/2a_handcoded_comparison.json)</sub>\n\n"
            f"**Question:** {r['question']}.\n\n"
            + _table(["", "USL", "Hand-coded"], rows) + diff
            + f"\n**The hand-coder's mapping steps** (each a fact about the sources that someone must know and "
              f"keep current):\n\n{steps}\n<!-- END generated -->")


def main() -> int:
    (DOCS / "02_exploratory_queries.md").write_text(render_02())
    (DOCS / "03_usl.md").write_text(render_03())
    f04 = DOCS / "04_time_saved.md"
    if f04.exists():
        text = f04.read_text()
        block = render_04_block()
        new = re.sub(r"<!-- BEGIN generated -->.*?<!-- END generated -->", lambda _m: block, text, flags=re.S)
        f04.write_text(new)
    print("rendered 02_exploratory_queries.md, 03_usl.md" + (", 04 block" if f04.exists() else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
